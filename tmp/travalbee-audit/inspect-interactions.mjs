import { chromium } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width:390, height:844 }, isMobile:true });
const result = { errors: [] };
page.on('pageerror', error => result.errors.push(error.message.slice(0, 400)));
try {
  await page.goto('https://travalbee.com', {waitUntil:'domcontentloaded',timeout:20000});
  const decline = page.getByRole('button', {name:'Decline', exact:true});
  await decline.waitFor({timeout:10000});
  result.ctaBeforeDismissal = await page.getByRole('link', {name:/Begin Your Journey/}).boundingBox();
  await decline.click();
  await page.screenshot({path:'tmp/travalbee-audit/home-mobile-dismissed.png'});
  await page.getByRole('link', {name:/Begin Your Journey/}).click();
  const destination = page.getByPlaceholder('Where do you wish to disappear?');
  await destination.fill('Paris');
  const suggestion = page.locator('.pac-item').first();
  await suggestion.waitFor({state:'visible',timeout:12000});
  result.suggestions = await page.locator('.pac-item').allTextContents();
  await suggestion.click();
  await page.waitForTimeout(700);
  result.formText = await page.locator('body').innerText();
  result.formHeight = await page.evaluate(() => document.documentElement.scrollHeight);
  await page.screenshot({path:'tmp/travalbee-audit/form-mobile-expanded.png',fullPage:true});
  await page.getByRole('button',{name:'Tailor My Trip',exact:true}).click();
  await page.waitForTimeout(700);
  await page.getByRole('button',{name:'Inspire Me',exact:true}).click();
  await page.waitForTimeout(700);
  result.destinationAfterModeRoundtrip = await destination.inputValue();
  await page.goto('https://travalbee.com/sample',{waitUntil:'domcontentloaded',timeout:20000});
  await page.waitForTimeout(1800);
  await page.screenshot({path:'tmp/travalbee-audit/sample-mobile-dismissed.png'});
  result.sampleLinks = await page.locator('a').evaluateAll(nodes => nodes.map(n=>({text:n.innerText,href:n.getAttribute('href')})));
} catch (error) { result.error=error.message.slice(0,1000); }
await writeFile('tmp/travalbee-audit/interactions.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
await browser.close();
